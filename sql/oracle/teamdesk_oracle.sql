SET FEEDBACK ON

-- [Oracle vs SQL Server] SELECT TOP 3 ... -> ... FETCH FIRST 3 ROWS ONLY (Oracle 12c+)
SELECT department_name, employee_count, avg_salary, total_payroll
FROM vw_department_summary
ORDER BY employee_count DESC, department_name;

-- Window functions (ROW_NUMBER ... OVER (PARTITION BY ...)) work the same in both databases.
SELECT department_name, name, salary
FROM (
    SELECT department_name, name, salary,
           ROW_NUMBER() OVER (PARTITION BY department_id ORDER BY salary DESC, id) AS salary_rank
    FROM vw_employee_details
)
WHERE salary_rank = 1
ORDER BY salary DESC
FETCH FIRST 3 ROWS ONLY;
