SET SERVEROUTPUT ON
SET FEEDBACK OFF
-- SQL*Plus display settings (they only affect how results print).
SET LINESIZE 160 PAGESIZE 100
COLUMN department_name FORMAT A18
COLUMN name FORMAT A18
COLUMN avg_salary FORMAT 99,99,99,999.99
COLUMN total_payroll FORMAT 99,99,99,999

-- [Oracle vs SQL Server] Before 23ai there is no DROP ... IF EXISTS, so a PL/SQL block drops
-- whatever exists. Scripts end PL/SQL blocks with "/" on its own line instead of "GO".
BEGIN
    FOR obj IN (
        SELECT object_name, object_type
        FROM user_objects
        WHERE object_type IN ('VIEW', 'PROCEDURE', 'TABLE')
          AND object_name IN ('VW_DEPARTMENT_SUMMARY', 'VW_EMPLOYEE_DETAILS', 'USP_ADD_EMPLOYEE',
                              'EMPLOYEES', 'DEPARTMENTS')
    ) LOOP
        EXECUTE IMMEDIATE 'DROP ' || obj.object_type || ' ' || obj.object_name
            || CASE WHEN obj.object_type = 'TABLE' THEN ' CASCADE CONSTRAINTS PURGE' END;
    END LOOP;
END;
/

-- ---------------------------------------------------------------------------
-- 1. Schema
-- ---------------------------------------------------------------------------

-- [Oracle vs SQL Server] IDENTITY(1,1)  ->  GENERATED BY DEFAULT AS IDENTITY (Oracle 12c+)
--                        NVARCHAR(n)    ->  VARCHAR2(n CHAR)  (length in characters, not bytes)
--                        DECIMAL(12,2)  ->  NUMBER(12,2)
CREATE TABLE departments (
    id   NUMBER GENERATED BY DEFAULT AS IDENTITY
         CONSTRAINT pk_departments PRIMARY KEY,
    name VARCHAR2(100 CHAR) NOT NULL
         CONSTRAINT uq_departments_name UNIQUE
);

-- [Oracle vs SQL Server] DATE in Oracle also stores a time of day, so TRUNC(SYSDATE) keeps
-- only the date part. SQL Server's DATE type has no time, and GETDATE()/SYSDATETIME() -> SYSDATE.
CREATE TABLE employees (
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY
                  CONSTRAINT pk_employees PRIMARY KEY,
    name          VARCHAR2(120 CHAR) NOT NULL,
    email         VARCHAR2(254 CHAR) NOT NULL,
    role          VARCHAR2(100 CHAR) NOT NULL,
    salary        NUMBER(12, 2) NOT NULL
                  CONSTRAINT ck_employees_salary CHECK (salary >= 0),
    department_id NUMBER NOT NULL
                  CONSTRAINT fk_employees_departments REFERENCES departments (id),
    joined_on     DATE DEFAULT TRUNC(SYSDATE) NOT NULL
);

-- [Oracle vs SQL Server] Oracle compares strings case-sensitively, so a plain UNIQUE(email)
-- would allow 'A@x.com' and 'a@x.com'. A function-based unique index on LOWER(email)
-- gives the same case-insensitive rule SQL Server gets from its default collation.
CREATE UNIQUE INDEX uq_employees_email_ci ON employees (LOWER(email));

-- Like SQL Server, Oracle does not index foreign keys automatically.
CREATE INDEX ix_employees_department_id ON employees (department_id);

