-- ---------------------------------------------------------------------------
-- 3. View: employees with their department name
-- ---------------------------------------------------------------------------

-- [Oracle vs SQL Server] CREATE OR ALTER VIEW -> CREATE OR REPLACE VIEW
CREATE OR REPLACE VIEW vw_employee_details AS
SELECT
    e.id,
    e.name,
    e.email,
    e.role,
    e.salary,
    e.joined_on,
    e.department_id,
    d.name AS department_name
FROM employees e
JOIN departments d ON d.id = e.department_id;

-- ---------------------------------------------------------------------------
-- 4. Procedure: validate and add one employee
-- ---------------------------------------------------------------------------

-- [Oracle vs SQL Server]
--   * Parameters are declared with IN / OUT and can borrow column types with %TYPE.
--   * THROW 50001, 'msg', 1   ->  RAISE_APPLICATION_ERROR(-20001, 'msg')  (codes -20000..-20999)
--   * SCOPE_IDENTITY()        ->  INSERT ... RETURNING id INTO p_new_id
--   * A procedure can't simply SELECT rows back to the caller as SQL Server's can; it returns
--     the new id through the OUT parameter (or a SYS_REFCURSOR) and the caller queries the view.
--   * The empty string '' IS NULL in Oracle, so one IS NULL check covers blank values too.
--   * The procedure leaves COMMIT to the caller, the usual Oracle convention.
CREATE OR REPLACE PROCEDURE usp_add_employee (
    p_name          IN  employees.name%TYPE,
    p_email         IN  employees.email%TYPE,
    p_role          IN  employees.role%TYPE,
    p_salary        IN  employees.salary%TYPE,
    p_department_id IN  employees.department_id%TYPE,
    p_joined_on     IN  employees.joined_on%TYPE DEFAULT NULL,
    p_new_id        OUT employees.id%TYPE
) AS
    v_department_count NUMBER;
BEGIN
    IF TRIM(p_name) IS NULL OR TRIM(p_email) IS NULL OR TRIM(p_role) IS NULL THEN
        RAISE_APPLICATION_ERROR(-20003, 'Name, email and role are required.');
    END IF;

    IF p_salary IS NULL OR p_salary < 0 THEN
        RAISE_APPLICATION_ERROR(-20003, 'Salary must be zero or more.');
    END IF;

    SELECT COUNT(*) INTO v_department_count FROM departments WHERE id = p_department_id;
    IF v_department_count = 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Department does not exist.');
    END IF;

    -- No separate "email exists?" query: the unique index enforces it atomically, so two
    -- sessions can't race past a check. A violation raises DUP_VAL_ON_INDEX, handled below.
    INSERT INTO employees (name, email, role, salary, department_id, joined_on)
    VALUES (TRIM(p_name), LOWER(TRIM(p_email)), TRIM(p_role), p_salary, p_department_id,
            NVL(p_joined_on, TRUNC(SYSDATE)))
    RETURNING id INTO p_new_id;
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        RAISE_APPLICATION_ERROR(-20002, 'An employee with this email already exists.');
END usp_add_employee;
/

-- ---------------------------------------------------------------------------
-- 5. Report: employee count and salary statistics per department
-- ---------------------------------------------------------------------------

-- [Oracle vs SQL Server] COALESCE works in both; NVL is the traditional Oracle equivalent.
-- ROUND(x, 2) here vs CAST(x AS DECIMAL(12,2)) in SQL Server.
CREATE OR REPLACE VIEW vw_department_summary AS
SELECT
    d.id                            AS department_id,
    d.name                          AS department_name,
    COUNT(e.id)                     AS employee_count,
    ROUND(NVL(AVG(e.salary), 0), 2) AS avg_salary,
    NVL(MIN(e.salary), 0)           AS min_salary,
    NVL(MAX(e.salary), 0)           AS max_salary,
    NVL(SUM(e.salary), 0)           AS total_payroll
FROM departments d
LEFT JOIN employees e ON e.department_id = d.id
GROUP BY d.id, d.name;

