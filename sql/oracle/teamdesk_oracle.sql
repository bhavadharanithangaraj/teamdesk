DECLARE
    v_new_id employees.id%TYPE;
    v_engineering departments.id%TYPE;
BEGIN
    SELECT id INTO v_engineering FROM departments WHERE name = 'Engineering';

    usp_add_employee('Rohan Mehta', 'Rohan.Mehta@teamdesk.dev', 'Frontend Engineer', 1500000,
                     v_engineering, DATE '2022-01-10', v_new_id);
    DBMS_OUTPUT.PUT_LINE('Added employee id ' || v_new_id);

    -- Same email in different case: rejected by the LOWER(email) unique index.
    BEGIN
        usp_add_employee('Rohan M', 'rohan.mehta@TEAMDESK.dev', 'Engineer', 1000000,
                         v_engineering, NULL, v_new_id);
    EXCEPTION
        WHEN OTHERS THEN DBMS_OUTPUT.PUT_LINE('Expected error: ' || SQLERRM);
    END;

    -- Unknown department.
    BEGIN
        usp_add_employee('Test User', 'test.user@teamdesk.dev', 'Engineer', 1000000,
                         999, NULL, v_new_id);
    EXCEPTION
        WHEN OTHERS THEN DBMS_OUTPUT.PUT_LINE('Expected error: ' || SQLERRM);
    END;

    COMMIT;
END;
